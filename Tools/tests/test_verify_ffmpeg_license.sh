#!/bin/bash
# Cases for Tools/verify_ffmpeg_license.sh.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPT="$HERE/../verify_ffmpeg_license.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FAILURES=0

expect_exit() {
  local label="$1" want="$2" dir="$3"
  "$SCRIPT" "$dir" >/dev/null 2>&1
  local got=$?
  if [ "$got" -eq "$want" ]; then
    echo "  ✓ $label"
  else
    echo "  ✗ ${label}: expected exit ${want}, got $got"
    FAILURES=$((FAILURES + 1))
  fi
}

make_config() {
  local dir="$1" gpl="$2" nonfree="$3"
  mkdir -p "$dir"
  cat > "$dir/config.h" <<EOF
/* Automatically generated by configure - do not modify! */
#define FFMPEG_CONFIGURATION "--enable-cross-compile"
#define CONFIG_GPL $gpl
#define CONFIG_NONFREE $nonfree
#define CONFIG_VERSION3 0
EOF
}

echo "test_verify_ffmpeg_license"

make_config "$TMP/clean" 0 0
expect_exit "an LGPL build passes" 0 "$TMP/clean"

make_config "$TMP/gpl" 1 0
expect_exit "CONFIG_GPL=1 is refused" 1 "$TMP/gpl"

make_config "$TMP/nonfree" 0 1
expect_exit "CONFIG_NONFREE=1 is refused" 1 "$TMP/nonfree"

make_config "$TMP/both" 1 1
expect_exit "both at 1 is refused" 1 "$TMP/both"

mkdir -p "$TMP/missing"
expect_exit "a missing config.h is refused (nothing passes silently)" 1 "$TMP/missing"

# A built binary carries its license string and its configure line.
expect_binary() {
  local label="$1" want="$2" file="$3"
  "$SCRIPT" --binary "$file" >/dev/null 2>&1
  local got=$?
  if [ "$got" -eq "$want" ]; then
    echo "  ✓ $label"
  else
    echo "  ✗ ${label}: expected exit ${want}, got $got"
    FAILURES=$((FAILURES + 1))
  fi
}
# As FFmpeg writes it: each library's license string after its own prefix.
printf 'x\0libavutil license: LGPL version 2.1 or later\0libavcodec license: LGPL version 2.1 or later\0--prefix=/umbel --enable-cross-compile --enable-static\0' > "$TMP/lgpl.bin"
printf 'x\0libavutil license: GPL version 2 or later\0--prefix=/umbel --enable-cross-compile --enable-gpl\0' > "$TMP/gpl.bin"
printf 'x\0libavutil license: LGPL version 2.1 or later\0--prefix=/umbel --enable-cross-compile --enable-nonfree\0' > "$TMP/nonfree.bin"
printf 'x\0libavutil license: LGPL version 3 or later\0--prefix=/umbel --enable-cross-compile --enable-version3\0' > "$TMP/v3.bin"
printf 'x\0libavutil license: LGPL version 2.1 or later\0libavcodec license: LGPL version 3 or later\0--prefix=/umbel --enable-cross-compile\0' > "$TMP/mixed.bin"
expect_binary "a binary saying LGPL 2.1 or later passes" 0 "$TMP/lgpl.bin"
expect_binary "a GPL binary fails" 1 "$TMP/gpl.bin"
expect_binary "a nonfree configure line fails" 1 "$TMP/nonfree.bin"
expect_binary "LGPL version 3 fails" 1 "$TMP/v3.bin"
expect_binary "a missing binary fails" 1 "$TMP/absent.bin"
expect_binary "one library of several not LGPL 2.1 fails" 1 "$TMP/mixed.bin"

if [ "$FAILURES" -eq 0 ]; then
  echo "✓ all passed"
  exit 0
fi
echo "✗ ${FAILURES} failed"
exit 1
